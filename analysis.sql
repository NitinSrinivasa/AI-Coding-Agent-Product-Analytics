-- ============================================================
-- 2. SESSION-LEVEL VIEW
-- ============================================================

CREATE OR REPLACE VIEW sessions AS
SELECT
    session_id,
    date,
    array_length(turns) AS turns_count
FROM read_json_auto(
    '/Users/nitin/Downloads/date=2026-06-07/shard-0000.jsonl.gz'
);


-- Preview session-level data
SELECT *
FROM sessions
LIMIT 20;


-- Summary statistics for session length
SELECT
    AVG(turns_count) AS avg_turns,
    MEDIAN(turns_count) AS median_turns,
    MAX(turns_count) AS max_turns
FROM sessions;


-- Percentage of sessions with exactly 1 turn
SELECT
    COUNT(*) FILTER (WHERE turns_count = 1)
        * 100.0 / COUNT(*) AS one_turn_pct
FROM sessions;


-- Percentage of sessions with more than 5 turns
SELECT
    COUNT(*) FILTER (WHERE turns_count > 5)
        * 100.0 / COUNT(*) AS more_than_5_turns_pct
FROM sessions;


-- Percentage of sessions with more than 10 turns
SELECT
    COUNT(*) FILTER (WHERE turns_count > 10)
        * 100.0 / COUNT(*) AS more_than_10_turns_pct
FROM sessions;


-- Average turn count among long sessions
SELECT
    AVG(turns_count) AS avg_turns_long_sessions
FROM sessions
WHERE turns_count > 10;


-- Share of total turn volume generated by sessions with >10 turns
SELECT
    SUM(turns_count) FILTER (WHERE turns_count > 10)
        * 100.0 / SUM(turns_count) AS long_session_turn_share_pct
FROM sessions;


