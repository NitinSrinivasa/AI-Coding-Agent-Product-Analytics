-- ============================================================
-- 4. FLATTEN LLM CALLS
-- ============================================================

-- Use a 100-session sample for deeper LLM-call analysis
-- because flattening the full nested dataset exceeded available memory.

CREATE OR REPLACE VIEW llm_calls_flat AS
SELECT
    s.session_id,
    array_length(s.turns) AS turns_count,
    t.turn.turn_id,
    l.call.message_id,
    l.call.timestamp,
    l.call.model,
    l.call.duration_ms,
    l.call.initiator_type,
    l.call.status_code,
    l.call.result
FROM (
    SELECT *
    FROM read_json_auto(
        '/Users/nitin/Downloads/date=2026-06-07/shard-0000.jsonl.gz'
    )
    LIMIT 100
) AS s,
UNNEST(s.turns) AS t(turn),
UNNEST(t.turn.llm_calls) AS l(call);


-- Preview flattened LLM-call data
SELECT *
FROM llm_calls_flat
LIMIT 20;


-- ============================================================
-- 5. SHORT VS LONG SESSION ANALYSIS
-- Definitions:
-- Short = <= 5 turns
-- Long  = > 10 turns
-- ============================================================

-- Compare average LLM-call duration
SELECT
    CASE
        WHEN turns_count <= 5 THEN 'short'
        WHEN turns_count > 10 THEN 'long'
    END AS session_group,
    AVG(duration_ms) AS avg_duration_ms,
    COUNT(*) AS llm_call_count
FROM llm_calls_flat
WHERE turns_count <= 5
   OR turns_count > 10
GROUP BY session_group;


-- Compare LLM-call success rates
SELECT
    CASE
        WHEN turns_count <= 5 THEN 'short'
        WHEN turns_count > 10 THEN 'long'
    END AS session_group,
    COUNT(*) AS total_llm_calls,
    SUM(
        CASE
            WHEN result = 'Success' THEN 1
            ELSE 0
        END
    ) AS successful_calls,
    SUM(
        CASE
            WHEN result = 'Success' THEN 1
            ELSE 0
        END
    ) * 100.0 / COUNT(*) AS success_rate_pct
FROM llm_calls_flat
WHERE turns_count <= 5
   OR turns_count > 10
GROUP BY session_group;


-- ============================================================
-- 6. LLM CALLS PER SESSION
-- ============================================================

CREATE OR REPLACE VIEW calls_per_session AS
SELECT
    session_id,
    turns_count,
    COUNT(*) AS llm_calls
FROM llm_calls_flat
GROUP BY session_id, turns_count;


-- Compare average LLM calls per short vs long session
SELECT
    CASE
        WHEN turns_count <= 5 THEN 'short'
        WHEN turns_count > 10 THEN 'long'
    END AS session_group,
    AVG(llm_calls) AS avg_llm_calls_per_session,
    COUNT(*) AS session_count
FROM calls_per_session
WHERE turns_count <= 5
   OR turns_count > 10
GROUP BY session_group;


-- ============================================================
-- 7. RESULT BREAKDOWN
-- ============================================================

SELECT
    CASE
        WHEN turns_count <= 5 THEN 'short'
        WHEN turns_count > 10 THEN 'long'
    END AS session_group,
    result,
    COUNT(*) AS result_count
FROM llm_calls_flat
WHERE turns_count <= 5
   OR turns_count > 10
GROUP BY session_group, result
ORDER BY session_group, result_count DESC;